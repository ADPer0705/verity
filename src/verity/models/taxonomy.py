"""Manipulation families Verity reasons about.

Every detector declares which families it was trained to recognise
(``targets`` in ``detector.yaml``); the selector, the report and the UI use
this to show *coverage*: which kinds of manipulation were actually examined,
by which evidence-grade methods, and which were not.
"""
from __future__ import annotations

from typing import Dict, List

FAMILIES: Dict[str, dict] = {
    "face_swap": {
        "label": "Face swap",
        "modalities": ["image", "video"],
        "description": "Identity replacement: one person's face transplanted onto another's "
                       "body (Deepfakes, FaceSwap, SimSwap, InSwapper, Roop and similar).",
    },
    "face_reenactment": {
        "label": "Face reenactment",
        "modalities": ["image", "video"],
        "description": "Expression or pose transfer while keeping the identity "
                       "(Face2Face, NeuralTextures, talking-head avatars driven by a source video).",
    },
    "lip_sync": {
        "label": "Lip sync",
        "modalities": ["video"],
        "description": "Mouth region re-rendered to match a different audio track "
                       "(Wav2Lip, LatentSync, dubbing tools).",
    },
    "face_synthesis": {
        "label": "Synthetic face",
        "modalities": ["image", "video"],
        "description": "A face that never existed, generated by a GAN or diffusion model "
                       "(StyleGAN, Stable Diffusion portraits, Midjourney).",
    },
    "image_synthesis": {
        "label": "AI-generated image",
        "modalities": ["image", "video"],
        "description": "Any fully generated image, faces or not (Stable Diffusion, DALL-E, "
                       "Midjourney, Flux, GANs).",
    },
    "image_editing": {
        "label": "Local image editing",
        "modalities": ["image"],
        "description": "Part of a real image replaced or inpainted (splicing, copy-move, "
                       "generative fill); detected by localisation methods.",
    },
    "video_synthesis": {
        "label": "AI-generated video",
        "modalities": ["video"],
        "description": "Fully generated video (Sora, Veo, Kling, Runway and similar).",
    },
    "audio_synthesis": {
        "label": "Synthetic or cloned voice",
        "modalities": ["audio", "video"],
        "description": "Text-to-speech or voice conversion impersonating a real speaker.",
    },
}

FAMILY_IDS: List[str] = list(FAMILIES)


def family_label(family_id: str) -> str:
    return FAMILIES.get(family_id, {}).get("label", family_id)
