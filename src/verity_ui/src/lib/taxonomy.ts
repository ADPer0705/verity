const LABELS = new Map(FAMILIES.map((family) => [family.id, family.label]))

export function familyLabel(id: string, families?: CoverageFamily[] | null): string {
  const fromApi = families?.find((family) => family.id === id)?.label
  return fromApi ?? LABELS.get(id) ?? id.replace(/_/g, ' ')
}

export type Lean = 'manipulated' | 'authentic' | 'undecided'

export interface FamilyCoverage {
  family: CoverageFamily
  /** Evidence-grade findings whose detector targets this family. */
  trained: Finding[]
  /** Research-only findings targeting this family — never counted. */
  untrained: Finding[]
  fake: number
  real: number
  uncertain: number
  lean: Lean | null
  examined: boolean
}

function leanOf(fake: number, real: number, uncertain: number): Lean | null {
  if (fake + real + uncertain === 0) return null
  if (fake > real && fake >= uncertain) return 'manipulated'
  if (real > fake && real >= uncertain) return 'authentic'
  return 'undecided'
}

/**
 * Fold a case's findings into the families relevant to its modality.
 *
 * A family counts as examined only when at least one evidence-grade detector
 * targeting it produced a finding; untrained heads are listed but never lean
 * the family one way or the other.
 */
export function caseCoverage(
  findings: Finding[],
  mediaType: MediaType,
  families: CoverageFamily[] = FAMILIES,
): FamilyCoverage[] {
  const relevant =
    mediaType === 'unknown'
      ? families
      : families.filter((family) => family.modalities.includes(mediaType))

  return relevant.map((family) => {
    const targeting = findings.filter((finding) => (finding.targets ?? []).includes(family.id))
    const trained = targeting.filter((finding) => finding.trained)
    const untrained = targeting.filter((finding) => !finding.trained)
    const count = (classification: Classification) =>
      trained.filter((finding) => finding.classification === classification).length
    const fake = count('FAKE')
    const real = count('REAL')
    const uncertain = count('UNCERTAIN')
    return {
      family,
      trained,
      untrained,
      fake,
      real,
      uncertain,
      lean: leanOf(fake, real, uncertain),
      examined: trained.length > 0,
    }
  })
}

