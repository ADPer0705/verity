#!/usr/bin/env python3
"""Regenerate docs/detectors.md from detector.yaml files and the weights manifest.

    uv run python scripts/gen_detector_table.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from verity.detect.detector_registry import DetectorRegistry  # noqa: E402
from verity.weights import load_manifest  # noqa: E402


def main() -> None:
    registry = DetectorRegistry(ROOT / "detectors")
    manifest = load_manifest(ROOT / "detectors" / "weights_manifest.yaml")
    rows = []
    for det_id, d in sorted(registry.list_detectors().items()):
        caps = d.capabilities
        targets = manifest.detectors.get(det_id, [])
        if targets:
            files = ", ".join(f"`{t.spec.name}` ({t.spec.effective_license(manifest)})" for t in targets)
        elif det_id in manifest.runtime_fetched:
            files = "fetched at first run: " + manifest.runtime_fetched[det_id]
        elif det_id in manifest.no_checkpoint:
            files = manifest.no_checkpoint[det_id]
        else:
            files = ""
        modality = "/".join(caps.media_types) + (" (temporal)" if d.video_mode else "")
        from verity.models.taxonomy import family_label
        targets = ", ".join(family_label(t) for t in d.targets) or "—"
        rows.append(f"| `{det_id}` | {d.name or det_id} | **{d.weights.tier}** | {modality} | {targets} | "
                    f"{d.architecture or ''} | {files} |")
    tiers = {}
    for d in registry.list_detectors().values():
        tiers[d.weights.tier] = tiers.get(d.weights.tier, 0) + 1
    summary = ", ".join(f"{n} {t}" for t, n in sorted(tiers.items(), key=lambda kv: -kv[1]))
    text = f"""# Detectors

{len(rows)} ported architectures: {summary}. Only **trained** detectors are
auto-selected; the others run on request (`--include-untrained`) and are
flagged as not evidence-grade. Generated by `scripts/gen_detector_table.py`
from `detectors/*/detector.yaml` and `detectors/weights_manifest.yaml`.

| id | name | tier | input | targets | architecture | weights (license) |
|---|---|---|---|---|---|---|
{chr(10).join(rows)}
"""
    (ROOT / "docs" / "detectors.md").write_text(text)
    print(f"wrote docs/detectors.md ({len(rows)} detectors: {summary})")


if __name__ == "__main__":
    main()
